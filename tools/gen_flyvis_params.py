"""Generate config/brain/flyvis_time_constants.yaml from the pinned flyvis ensemble (BRAIN-R-014).

Reads the 50 trained flyvis models (Lappalainen et al. 2024, MIT) straight from the verified zip in
data/raw/flyvis_pretrained, without unpacking it. Checkpoints are loaded with
`torch.load(weights_only=True)`, which refuses arbitrary pickled objects.

flyvis stores one membrane time constant per cell type, in seconds, in the order in which types
first appear in its connectome's node list (`groupby(sort=False)`). The table gives, per FlyWire
cell type, the ensemble median in ms. Name mapping: flyvis R1..R6 -> FlyWire "R1-6" (mean of the
six), CT1(Lo1)/CT1(M10) -> "CT1" (mean of the two compartments); all other names are identical.

Usage: python tools/gen_flyvis_params.py
"""

from __future__ import annotations

import io
import json
import re
import sys
import zipfile
from pathlib import Path

import numpy as np
import torch

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw" / "flyvis_pretrained"
OUT = ROOT / "config" / "brain" / "flyvis_time_constants.yaml"
GROUPS = {"R1-6": ["R1", "R2", "R3", "R4", "R5", "R6"], "CT1": ["CT1(Lo1)", "CT1(M10)"]}


def main() -> int:
    nodes = json.loads((RAW / "fib25-fib19_v2.2.json").read_text(encoding="utf-8"))["nodes"]
    order: list[str] = []
    for node in nodes:
        if node["name"] not in order:
            order.append(node["name"])
    taus = []
    with zipfile.ZipFile(RAW / "results_pretrained_models.zip") as z:
        names = sorted(n for n in z.namelist() if n.endswith("chkpts/chkpt_00000"))
        for name in names:
            ck = torch.load(io.BytesIO(z.read(name)), weights_only=True, map_location="cpu")
            t = ck["network"]["nodes_time_const"].double().numpy()
            if t.shape != (len(order),):
                raise SystemExit(f"{name}: {t.shape} time constants, expected {len(order)}")
            taus.append(t)
        meta = z.read(names[0].replace("chkpts/chkpt_00000", "_meta.yaml")).decode("utf-8")
    train_dt_ms = 1000.0 * float(re.search(r"^\s*dt:\s*([0-9.eE-]+)", meta, re.M).group(1))
    # flyvis integrates with tau_eff = max(tau, dt): values below its training step are not
    # identifiable, so the effective value is used and flagged.
    taus = np.maximum(np.stack(taus) * 1000.0, train_dt_ms)  # s -> ms
    per_flyvis = {name: taus[:, i] for i, name in enumerate(order)}
    rows = {}
    for fw_type in sorted({*order, *GROUPS} - {n for g in GROUPS.values() for n in g}):
        src = GROUPS.get(fw_type, [fw_type])
        vals = np.mean([per_flyvis[s] for s in src], axis=0)  # per model
        rows[fw_type] = {
            "tau_ms": round(float(np.median(vals)), 3),
            "iqr_ms": [round(float(np.percentile(vals, 25)), 3), round(float(np.percentile(vals, 75)), 3)],
            "flyvis_types": src,
            "at_floor": bool(np.median(vals) <= train_dt_ms + 1e-9),
        }
    lines = [
        "# GENERATED by tools/gen_flyvis_params.py - do not edit by hand.",
        "# Graded-unit membrane time constants per FlyWire cell type (BRAIN-R-014): median over the",
        f"# {len(names)}-model flyvis ensemble (results_pretrained_models.zip, sha256 71c78d40...).",
        "source:",
        "  authors: Lappalainen J.K. et al.",
        "  year: 2024",
        "  doi: 10.1038/s41586-024-07939-3",
        "  where: flyvis pretrained ensemble, network.nodes_time_const (seconds), effective value max(tau, training dt)",
        "  license: MIT",
        f"models: {len(names)}",
        f"training_dt_ms: {train_dt_ms:g}   # at_floor: true = the type's tau is <= this; flyvis cannot resolve it further",
        "cell_types:",
    ]
    for k, v in rows.items():
        lines.append(f'  "{k}": {{tau_ms: {v["tau_ms"]}, iqr_ms: {v["iqr_ms"]}, flyvis_types: {json.dumps(v["flyvis_types"])}, at_floor: {str(v["at_floor"]).lower()}}}')
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} types from {len(names)} models")
    return 0


if __name__ == "__main__":
    sys.exit(main())
